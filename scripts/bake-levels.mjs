// Generates + proves every level (each song x easy / medium / hard stage) and writes src/game/levels.baked.js so the game
// loads them instantly. Levels whose bake is still up to date are kept; the rest are built in parallel (one worker each).
// Run with:  npm run bake      (a few minutes; only needed when the generator or level settings change)
// Add  --all  to rebuild every level.
import fs from 'node:fs';
import os from 'node:os';
import { Worker, isMainThread, parentPort, workerData } from 'node:worker_threads';
import { buildLevel, LEVEL_DEFS, levelSig, serializeLevel } from '../src/game/levelgen.js';

if (!isMainThread) {
  const def = LEVEL_DEFS.find((d) => d.id === workerData.id);
  const t = Date.now();
  const lv = buildLevel(def);
  parentPort.postMessage({ id: def.id, sig: levelSig(def), level: serializeLevel(lv), s: (Date.now() - t) / 1000 });
} else {
  const { default: OLD } = await import('../src/game/levels.baked.js');
  const all = process.argv.includes('--all');
  const keep = all ? [] : OLD.filter((b) => { const d = LEVEL_DEFS.find((q) => q.id === b.id); return d && b.sig === levelSig(d); });
  const todo = LEVEL_DEFS.filter((d) => !keep.some((b) => b.id === d.id));
  console.log(`keeping ${keep.length} up-to-date level(s); building ${todo.length}: ${todo.map((d) => `${d.id} ${d.song}/${d.tier}`).join(', ')}`);
  const max = Math.max(1, Math.min(todo.length, os.cpus().length - 1));
  const out = [...keep];
  let next = 0;
  const run = () => new Promise((resolve, reject) => {
    const go = () => {
      if (next >= todo.length) return resolve();
      const d = todo[next++];
      const w = new Worker(new URL(import.meta.url), { workerData: { id: d.id } });
      w.once('message', (m) => { out.push({ id: m.id, sig: m.sig, level: m.level }); console.log(`level ${m.id} ${d.song}/${d.tier}: built + proven in ${m.s.toFixed(1)} s`); });
      w.once('error', reject);
      w.once('exit', go);
    };
    go();
  });
  await Promise.all(Array.from({ length: max }, run));
  out.sort((a, b) => a.id - b.id);
  fs.writeFileSync(new URL('../src/game/levels.baked.js', import.meta.url), '// AUTO-GENERATED by scripts/bake-levels.mjs — do not edit.\nexport default ' + JSON.stringify(out) + ';\n');
  console.log(`wrote src/game/levels.baked.js (${out.length} levels)`);
}
