// Generates + proves all three levels and writes them to src/game/levels.baked.js so the game loads them instantly.
// Run with:  npm run bake      (takes about a minute; only needed when the generator or level settings change)
import fs from 'node:fs';
import { buildLevel, LEVEL_DEFS, levelSig, serializeLevel } from '../src/game/levelgen.js';

const out = [];
for (const def of LEVEL_DEFS) {
  const t = Date.now();
  const lv = buildLevel(def);
  out.push({ id: def.id, sig: levelSig(def), level: serializeLevel(lv) });
  console.log(`level ${def.id} ${def.name}: built + proven in ${((Date.now() - t) / 1000).toFixed(1)} s`);
}
fs.writeFileSync(new URL('../src/game/levels.baked.js', import.meta.url), '// AUTO-GENERATED by scripts/bake-levels.mjs — do not edit.\nexport default ' + JSON.stringify(out) + ';\n');
console.log('wrote src/game/levels.baked.js');
