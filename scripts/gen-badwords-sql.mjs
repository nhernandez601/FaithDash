// Writes supabase/badwords.sql from src/online/names.js, so the database blocks exactly the names the game blocks.
// Run after changing the word lists:  node scripts/gen-badwords-sql.mjs   then run the new file in Supabase (SQL Editor).
import fs from 'fs';
import { PARTS, WORDS, ASS_OK, JOKES, CODES, loosePattern } from '../src/online/names.js';
const q = (s) => "'" + s.replace(/'/g, "''") + "'";
const rows = (kind, list) => list.map((w) => `(${q(w)}, ${q(kind)})`).join(',\n  ');
const sql = `-- GENERATED by scripts/gen-badwords-sql.mjs from src/online/names.js. Do not edit by hand: change the lists there,
-- re-run the script, then run this file in Supabase (SQL Editor). Safe to run again.
-- The same gamer-name rules as the game (see names.js for how they work):
--   part  = blocked anywhere in the name (spaces/dots removed, letters may repeat)
--   word  = blocked as a whole word only
--   ass_ok = normal words ending in "ass" (class, grass...) that are allowed
--   joke  = a ready-made loose ("sounds like") pattern for joke names such as Hugh Jass, matched anywhere
--   code  = a number code (1488, 666) looked for in the name as typed
-- To block one more word right away without a game update:  insert into fd_bad_words values ('word', 'part');

create table if not exists public.fd_bad_words (word text not null, kind text not null, primary key (word, kind));
alter table public.fd_bad_words drop constraint if exists fd_bad_words_kind_check;
alter table public.fd_bad_words add constraint fd_bad_words_kind_check check (kind in ('part', 'word', 'ass_ok', 'joke', 'code'));
alter table public.fd_bad_words enable row level security;
revoke all on public.fd_bad_words from anon, authenticated;
insert into public.fd_bad_words (word, kind) values
  ${rows('part', PARTS)},
  ${rows('word', WORDS)},
  ${rows('ass_ok', ASS_OK)},
  ${rows('joke', JOKES.map(loosePattern))},
  ${rows('code', CODES)}
on conflict do nothing;

-- true when a name contains something blocked (same readings as readings() in names.js)
create or replace function public.fd_name_blocked(p_name text) returns boolean
language plpgsql stable security definer set search_path = public as $$
declare base text; r text; compact text; w text; sw text; i int := 0; rs text[]; typed text;
begin
  typed := translate(lower(p_name), '_.-', '   ');
  if exists (select 1 from fd_bad_words b where b.kind = 'code' and (position(b.word in typed) > 0 or position(replace(b.word, ' ', '') in replace(typed, ' ', '')) > 0)) then return true; end if;
  base := translate(lower(regexp_replace(p_name, '([a-z])([A-Z])', '\\1 \\2', 'g')), '_.-', '   ');
  r := translate(base, '0123456789', 'oizeasgtbg');
  rs := array[
    r,
    translate(base, '0123456789', 'olzeasgtbg'),
    translate(r, 'ly', 'ii'),
    replace(replace(translate(r, 'vq', 'uk'), 'ph', 'f'), 'ck', 'k')
  ];
  foreach r in array rs loop
    i := i + 1;
    compact := regexp_replace(r, '[^a-z]', '', 'g');
    if exists (select 1 from fd_bad_words b where b.kind = 'part' and compact ~ regexp_replace(b.word, '(.)', '\\1+', 'g')) then return true; end if;
    if exists (select 1 from fd_bad_words b where b.kind = 'joke' and compact ~ b.word) then return true; end if;
    for w in select x from regexp_split_to_table(r, '[^a-z]+') x where x <> '' union all select compact loop
      if exists (select 1 from fd_bad_words b where b.kind = 'word' and w ~ ('^' || regexp_replace(b.word, '(.)', '\\1+', 'g') || '$')) then return true; end if;
      sw := regexp_replace(w, '(.)\\1{2,}', '\\1\\1', 'g');
      if i <= 2 and sw like '%ass' and not exists (select 1 from fd_bad_words b where b.kind = 'ass_ok' and sw like '%' || b.word) then return true; end if;
    end loop;
  end loop;
  return false;
end $$;
revoke all on function public.fd_name_blocked(text) from public, anon, authenticated;

-- set / change my gamer name (replaces the version in leaderboard.sql: now uses the full filter)
create or replace function public.fd_set_name(p_player uuid, p_name text) returns text
language plpgsql security definer set search_path = public as $$
declare n text := btrim(regexp_replace(coalesce(p_name, ''), '\\s+', ' ', 'g'));
begin
  if n !~ '^[A-Za-z0-9 _.\\-]{3,16}$' or n !~ '[A-Za-z]' then raise exception 'bad_name'; end if;
  if fd_name_blocked(n) then raise exception 'bad_name'; end if;
  if exists (select 1 from fd_players where lower(name) = lower(n) and player_id <> p_player) then raise exception 'name_taken'; end if;
  insert into fd_players (player_id, name) values (p_player, n)
    on conflict (player_id) do update set name = excluded.name, updated_at = now();
  return n;
end $$;
grant execute on function public.fd_set_name(uuid, text) to anon;
`;
fs.writeFileSync(new URL('../supabase/badwords.sql', import.meta.url), sql);
console.log('wrote supabase/badwords.sql:', PARTS.length, 'parts,', WORDS.length, 'words,', ASS_OK.length, 'allowed -ass words,', JOKES.length, 'joke names,', CODES.length, 'codes');
