import { chromium } from 'playwright-core';
import { spawn } from 'child_process';
const srv = spawn('npx', ['vite', 'preview', '--port', '4173', '--strictPort'], { stdio: 'ignore' });
await new Promise((r) => setTimeout(r, 2500));
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--use-gl=swiftshader', '--enable-webgl', '--ignore-gpu-blocklist', '--no-sandbox'] });
const errs = [];
// icons
const ip = await b.newPage({ viewport: { width: 512, height: 512 } });
const svg = (await import('fs')).readFileSync('public/icon.svg', 'utf8');
await ip.setContent(`<body style="margin:0">${svg.replace('<svg', '<svg width="512" height="512"')}</body>`);
await ip.screenshot({ path: 'public/icon-512.png' });
await ip.setViewportSize({ width: 192, height: 192 });
await ip.setContent(`<body style="margin:0">${svg.replace('<svg', '<svg width="192" height="192"')}</body>`);
await ip.screenshot({ path: 'public/icon-192.png' });
const p = await b.newPage({ viewport: { width: 1280, height: 720 } });
p.on('console', (m) => { if (m.type() === 'error' || m.type() === 'warning') errs.push(m.type() + ': ' + m.text()); });
p.on('pageerror', (e) => errs.push('PAGEERROR: ' + e.message));
await p.goto('http://localhost:4173/');
await p.waitForTimeout(2000);
await p.screenshot({ path: 'tests/shots/01_start.png' });
console.log('screen:', await p.evaluate(() => document.querySelector('#screens > *')?.dataset.screen));
console.log(errs.join('\n') || 'no console errors');
await b.close(); srv.kill();
